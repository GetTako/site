import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const apiDir = path.resolve(__dirname, '../docs/17.api-reference');

function processDir(dir) {
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const fullPath = path.join(dir, file);
    if (fs.statSync(fullPath).isDirectory()) {
      // Automatically generate .navigation.yml for the folder
      const folderName = path.basename(fullPath);
      let folderIcon = 'i-lucide-folder';
      if (fullPath.includes('/pkg')) folderIcon = 'i-lucide-package';
      
      const folderTitle = folderName;
      const navPath = path.join(fullPath, '.navigation.yml');
      
      // We will overwrite the .navigation.yml to ensure the new title applies
      fs.writeFileSync(navPath, `title: ${folderTitle}\nnavigation:\n  icon: ${folderIcon}\n`);
      
      processDir(fullPath);
    } else if (fullPath.endsWith('.md')) {
      let content = fs.readFileSync(fullPath, 'utf-8');
      
      // Skip if already has frontmatter
      if (content.startsWith('---')) continue;

      // Extract title (usually the first H1 e.g., "# config")
      const titleMatch = content.match(/^#\s+(.+)$/m);
      const title = titleMatch ? titleMatch[1] : path.basename(file, '.md');
      
      // Customize icon based on folder or name
      let icon = 'i-lucide-box';
      if (fullPath.includes('/internal/')) icon = 'i-lucide-component';
      if (fullPath.includes('/pkg/')) icon = 'i-lucide-package';
      
      const frontmatter = `---
title: ${title}
description: "API Reference documentation for the ${title} package in Tako framework"
navigation:
  icon: ${icon}
---
`;
      
      // Remove the default gomarkdoc comment to make it cleaner
      content = content.replace(/<!-- Code generated by gomarkdoc\. DO NOT EDIT -->[\r\n]*/, '');
      
      fs.writeFileSync(fullPath, frontmatter + content);
    }
  }
}

console.log('=> Injecting frontmatter to API docs...');
processDir(apiDir);
console.log('=> Frontmatter injected successfully!');
